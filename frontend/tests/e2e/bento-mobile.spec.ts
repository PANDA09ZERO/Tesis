import { test, expect } from '@playwright/test';

test('bento: registros táctiles, edición única y diseño sin desbordamiento', async ({ page }, info) => {
  test.skip(info.project.name !== 'mobile', 'Flujo móvil');
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/login');
  await page.locator('input[type=email]').fill('user1@test.local');
  await page.locator('input[type=password]').fill('originalTest');
  await page.getByRole('button', { name: 'Iniciar Sesión', exact: true }).click();
  await expect(page).toHaveURL(/dashboard$/);
  await expect(page.getByRole('link', { name: 'Ver alumnos', exact: true })).toBeVisible();
  for (const route of ['/alumnos', '/profesores', '/admin/usuarios', '/reportes', '/documentos']) {
    await page.goto(route);
    const cards = page.locator('.mobile-bento-card');
    await expect(cards.first()).toBeVisible();
    await expect(page.getByRole('table')).toHaveCount(0);
    await cards.first().locator('summary').click();
    await expect(cards.first()).toHaveAttribute('open', '');
    await expect(cards.first().locator('.mobile-bento-content')).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.setViewportSize({ width: 320, height: 740 });
    expect(await page.locator('main').evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true);
    await page.screenshot({ path: info.outputPath(`bento-${route.replaceAll('/', '-')}.png`), fullPage: true });
    await page.setViewportSize({ width: 393, height: 851 });
    await cards.first().locator('summary').click();
    await expect(cards.first()).not.toHaveAttribute('open', '');
  }
  await page.goto('/calificaciones/oferta/1');
  await page.getByRole('combobox', { name: 'Evaluación', exact: true }).selectOption('1');
  const gradeCard = page.locator('.mobile-bento-card').filter({ has: page.locator('input[aria-label="Nota de Usuario 11"]') }).first();
  await gradeCard.locator('summary').click();
  const note = page.getByRole('spinbutton', { name: 'Nota de Usuario 11', exact: true });
  await expect(note).toHaveCount(1);
  await expect(note).toHaveValue(/^9(?:\.0+)?$/);
  await note.fill('0');
  await gradeCard.locator('summary').click();
  await gradeCard.locator('summary').click();
  await expect(note).toHaveValue('0');
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('bento-notas-320.png'), fullPage: true });
  await page.getByRole('button', { name: 'Cambiar a tema oscuro', exact: true }).click();
  await page.screenshot({ path: info.outputPath('bento-notas-oscuro.png'), fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  await expect(page.getByRole('table').first()).toBeVisible();
  await expect(note).toHaveCount(1);
  await expect(note).toHaveValue('0');
  await page.setViewportSize({ width: 393, height: 851 });
  await page.goto('/asistencias/oferta/1');
  const attendanceCard = page.locator('.mobile-bento-card').filter({ has: page.locator('select[aria-label="Asistencia de Usuario 11"]') }).first();
  await attendanceCard.locator('summary').click();
  await expect(page.getByRole('combobox', { name: 'Asistencia de Usuario 11', exact: true })).toBeVisible();
  await expect(page.getByRole('table')).toHaveCount(0);
  await page.goto('/admin/usuarios');
  await page.setViewportSize({ width: 1280, height: 900 });
  await expect(page.locator('.data-table > .mobile-bento-grid')).not.toBeVisible();
  await expect(page.getByRole('table')).toBeVisible();
  await page.setViewportSize({ width: 393, height: 851 });
  await page.goto('/modulos');
  await page.screenshot({ path: info.outputPath('bento-modulos.png'), fullPage: true });
  expect(errors).toEqual([]);
});
