test('expediente: acceso administrativo, validación y alumno sin trayectoria', async ({ page }) => {
  await login(page);
  const token = await page.evaluate(() => localStorage.getItem('token'));
  const headers = { Authorization: `Bearer ${token}` };
  expect((await page.request.get('/api/alumnos/0/expediente', { headers })).status()).toBe(400);
  expect((await page.request.get('/api/alumnos/999/expediente', { headers })).status()).toBe(404);
  for (const id of [2, 11, 21]) {
    const signed = await page.request.post('/api/auth/login', { data: { email: `user${id}@test.local`, password: 'originalTest' } });
    const body = await signed.json();
    expect((await page.request.get('/api/alumnos/1/expediente', { headers: { Authorization: `Bearer ${body.data.token}` } })).status()).toBe(403);
  }
  await page.getByRole('button', { name: /Usuario 13 A3/ }).click();
  await expect(page.getByText('Este alumno todavía no tiene registros académicos.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Imprimir libreta seleccionada' })).toBeDisabled();
  await expect(page.locator('body > .student-report-print')).toHaveCount(0);
});
test('expediente: error recuperable y cambio de alumno sin libreta anterior', async ({ page }) => {
  await login(page);
  await page.route('**/api/alumnos/1/expediente', route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ success: false, message: 'Fallo de expediente' }) }));
  await page.getByRole('button', { name: /Usuario 11 A1/ }).click();
  await expect(page.getByRole('alert')).toContainText('Fallo de expediente');
  await expect(page.locator('body > .student-report-print')).toHaveCount(0);
  await page.unroute('**/api/alumnos/1/expediente');
  await page.getByRole('button', { name: 'Reintentar', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Periodo de la libreta', exact: true })).toBeVisible();
  await page.getByText('Cambiar alumno', { exact: true }).click();
  await page.getByRole('button', { name: /Usuario 12 A2/ }).click();
  await expect(page.getByRole('heading', { name: 'Usuario 12', exact: true })).toBeVisible();
  await expect(page.locator('body > .student-report-print')).not.toContainText('A1');
});

test('expediente: adjunto persistente y asociado solo al alumno seleccionado', async ({ page }, info) => {
  await login(page);
  const token = await page.evaluate(() => localStorage.getItem('token'));
  const headers = { Authorization: `Bearer ${token}` };
  const created = await page.request.post('/api/documentos/categorias', { headers, data: { nombre: `Expediente ${info.project.name}` } });
  expect(created.status()).toBe(201);
  const category = (await created.json()).data.id;
  await page.reload();
  await page.getByRole('button', { name: 'Expediente estudiantil', exact: true }).click();
  await page.getByRole('button', { name: /Usuario 11 A1/ }).click();
  await page.getByRole('button', { name: 'Documentos vinculados', exact: true }).click();
  await page.getByRole('button', { name: 'Adjuntar al expediente', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.locator('input[type=file]').setInputFiles('public/assets/logo.png');
  const title = `Constancia ${info.project.name}`;
  await dialog.locator('input[maxlength="255"]').fill(title);
  await dialog.locator('select').selectOption(String(category));
  const saved = page.waitForResponse(response => response.url().endsWith('/api/documentos/upload') && response.request().method() === 'POST');
  await dialog.getByRole('button', { name: 'Subir archivo', exact: true }).click();
  expect((await saved).status()).toBe(201);
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  const own = await page.request.get('/api/alumnos/1/expediente', { headers });
  expect((await own.json()).data.documentos.some((d: { titulo: string }) => d.titulo === title)).toBe(true);
  const other = await page.request.get('/api/alumnos/2/expediente', { headers });
  expect((await other.json()).data.documentos.some((d: { titulo: string }) => d.titulo === title)).toBe(false);
  await page.getByRole('button', { name: 'Solicitudes', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Crear formulario', exact: true })).toBeVisible();
});
